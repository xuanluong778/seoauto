"""Classify plugin HTTP errors for Celery retry vs blocked/failed."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

import requests

# Plugin / SaaS error codes that must never retry.
BLOCKED_CODES = frozenset(
    {
        "seoauto_invalid_post",
        "seoauto_invalid_body",
        "seoauto_invalid_entitlement",
        "seoauto_bad_signature",
        "seoauto_plugin_locked",
        "seoauto_not_connected",
        "seoauto_feature_denied",
        "seoauto_post_type_denied",
        "seoauto_article_exists",
        "seoauto_entitlement_denied",
        "entitlement_denied",
        "expired",
        "canceled",
        "cancelled",
        "suspended",
        "revoked",
        "validation_error",
        "wordfence_blocked",
    }
)

WORDFENCE_BODY_MARKERS = (
    "wordfence",
    "generated by wordfence",
    "your access to this site has been limited",
    "waf_block",
    "blocked by wordfence",
)

RETRYABLE_HTTP = frozenset({502, 503, 504})


@dataclass(frozen=True)
class ErrorClassification:
    retryable: bool
    blocked: bool
    error_code: str
    message: str
    http_status: int | None = None


def _extract_error_code(body: dict[str, Any] | None, http_status: int) -> str:
    if not isinstance(body, dict):
        return f"http_{http_status}"
    code = body.get("code") or body.get("error_code")
    if isinstance(code, str) and code.strip():
        return code.strip()
    if isinstance(body.get("data"), dict):
        nested = body["data"].get("code") or body["data"].get("status")
        if isinstance(nested, str) and nested.strip():
            return nested.strip()
    detail = body.get("detail")
    if isinstance(detail, dict) and detail.get("code"):
        return str(detail["code"])
    return f"http_{http_status}"


def _extract_message(body: dict[str, Any] | None, fallback: str) -> str:
    if not isinstance(body, dict):
        return fallback[:2000]
    for key in ("message", "detail"):
        val = body.get(key)
        if isinstance(val, str) and val.strip():
            return val.strip()[:2000]
        if isinstance(val, dict) and val.get("message"):
            return str(val["message"])[:2000]
    return fallback[:2000]


def is_requests_network_error(exc: BaseException) -> bool:
    if isinstance(exc, requests.exceptions.Timeout):
        return True
    if isinstance(exc, requests.exceptions.ConnectionError):
        return True
    msg = str(exc).lower()
    needles = (
        "timed out",
        "timeout",
        "name or service not known",
        "failed to resolve",
        "connection refused",
        "connection reset",
        "network is unreachable",
        "temporary failure in name resolution",
    )
    return any(n in msg for n in needles)


def is_wordfence_block(*, http_status: int, body_text: str = "", headers: dict[str, str] | None = None) -> bool:
    """Detect Wordfence WAF 403 before plugin REST (HTML block page, not JSON seoauto_*)."""
    if http_status != 403:
        return False
    lower = (body_text or "").lower()
    if lower.strip().startswith("{") and '"code"' in lower and "seoauto_" in lower:
        return False
    for marker in WORDFENCE_BODY_MARKERS:
        if marker in lower:
            return True
    for name in (headers or {}):
        ln = str(name).lower()
        if ln.startswith("x-wordfence") or ln.startswith("x-wf-"):
            return True
    return False


def classify_http_response(
    http_status: int,
    body: dict[str, Any] | None,
    *,
    raw_text: str = "",
    endpoint: str = "",
) -> ErrorClassification:
    code = _extract_error_code(body, http_status)
    message = _extract_message(body, raw_text or f"HTTP {http_status}")
    lower = code.lower()
    path = endpoint or ""

    if is_wordfence_block(http_status=http_status, body_text=raw_text, headers=None):
        msg = f"Wordfence blocked {path or 'REST endpoint'} (HTTP 403). Check Live Traffic manually."
        return ErrorClassification(False, True, "wordfence_blocked", msg, http_status)

    if lower in BLOCKED_CODES or lower.startswith("seoauto_plugin_locked"):
        return ErrorClassification(False, True, lower, message, http_status)

    if http_status in (401, 403):
        if any(x in lower for x in ("expired", "revoked", "canceled", "cancelled", "suspended", "locked", "entitlement")):
            return ErrorClassification(False, True, lower, message, http_status)
        if lower in ("seoauto_bad_signature", "seoauto_not_connected"):
            return ErrorClassification(False, True, lower, message, http_status)

    if http_status in RETRYABLE_HTTP:
        return ErrorClassification(True, False, lower, message, http_status)

    if 400 <= http_status < 500:
        return ErrorClassification(False, False, lower, message, http_status)

    if http_status >= 500:
        return ErrorClassification(True, False, lower, message, http_status)

    if http_status >= 400:
        return ErrorClassification(False, False, lower, message, http_status)

    return ErrorClassification(False, False, "ok", message, http_status)


def classify_exception(exc: BaseException) -> ErrorClassification:
    if is_requests_network_error(exc):
        return ErrorClassification(True, False, "network_error", str(exc)[:2000])
    msg = str(exc)
    if re.search(r"(?i)(validation|invalid|signature|entitlement|expired|revoked)", msg):
        return ErrorClassification(False, True, "validation_error", msg[:2000])
    return ErrorClassification(False, False, "unexpected_error", msg[:2000])


def backoff_seconds(retry_count: int, *, base: float = 30.0, cap: float = 3600.0) -> float:
    """Exponential backoff: 30s, 60s, 120s, ... capped at 1 hour."""
    attempt = max(0, int(retry_count))
    delay = min(cap, base * (2**attempt))
    return float(delay)
